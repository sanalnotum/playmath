let LANG = LS.get('pm_lang', 'tr');
if (!I18N[LANG]) LANG = 'tr';

function t(k, v) {
  let s = I18N[LANG][k];
  if (s === undefined) s = I18N.tr[k];
  if (s === undefined) return k;
  if (v && typeof s === 'string') for (const x in v) s = s.split('{' + x + '}').join(v[x]);
  return s;
}
function setLang(l) { LANG = l; LS.set('pm_lang', l); document.documentElement.lang = l; }
